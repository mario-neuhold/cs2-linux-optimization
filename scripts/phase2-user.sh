#!/usr/bin/env bash
# =============================================================================
# CS2 Performance Optimization — Phase 2: User-level changes
# Tasks: 2.1-2.6 (gamemode, autoexec, launch options instructions)
# Does NOT require sudo (except gamemode.ini which goes to /etc).
# No reboot required.
# =============================================================================

set -euo pipefail

BOLD='\033[1m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
NC='\033[0m'

log()  { echo -e "${BOLD}[cs2-opt]${NC} $*"; }
ok()   { echo -e "${GREEN}  ✓${NC} $*"; }
warn() { echo -e "${YELLOW}  ⚠${NC} $*"; }

echo ""
echo -e "${BOLD}=== CS2 Performance Optimization — Phase 2 ===${NC}"
echo ""

# -----------------------------------------------------------------------------
# TASK 2.1 — Enable gamemoded user service
# Spec: gamemode-config — Gamemoded Daemon Active at Boot
# -----------------------------------------------------------------------------
log "Task 2.1 — Enabling gamemoded user service"

systemctl --user enable --now gamemoded 2>/dev/null && ok "gamemoded.service enabled and started" || warn "Could not enable gamemoded — check 'systemctl --user status gamemoded'"

# Ensure gamemoded starts at boot even without an active login session
loginctl enable-linger "$USER" 2>/dev/null && ok "loginctl linger enabled for $USER" || warn "loginctl enable-linger failed — gamemoded may not start at boot automatically"

# -----------------------------------------------------------------------------
# TASK 2.2 — Write /etc/gamemode.ini
# Spec: gamemode-config — Gamemode INI Configuration
# Note: renice=10 in gamemode.ini means nice=-10 for game process (gamemode convention)
# -----------------------------------------------------------------------------
log "Task 2.2 — Writing /etc/gamemode.ini"

GAMEMODE_INI="/etc/gamemode.ini"

if [[ -f "$GAMEMODE_INI" ]]; then
    warn "$GAMEMODE_INI already exists — backing up to ${GAMEMODE_INI}.bak"
    sudo cp "$GAMEMODE_INI" "${GAMEMODE_INI}.bak"
fi

sudo tee "$GAMEMODE_INI" > /dev/null << 'EOF'
; CS2 Performance Optimization — gamemode configuration
; renice=10 → game process runs at nice=-10 (high priority)
; CPU governor management is handled by cs2-performance-governor.service

[general]
renice=10
ioprio=0
inhibit_screensaver=1

[filter]
whitelist=cs2
EOF

ok "/etc/gamemode.ini written"

# Verify gamemoded self-test
log "Task 2.2 — Running gamemoded self-test"
if gamemoded -t &>/dev/null; then
    ok "gamemoded -t passed ✓"
else
    warn "gamemoded -t failed — check 'gamemoded -t' output manually"
fi

# -----------------------------------------------------------------------------
# TASK 2.3 — Create CS2 cfg directory
# Spec: cs2-autoexec — Autoexec File Exists and Is Sourced
# -----------------------------------------------------------------------------
log "Task 2.3 — Creating CS2 cfg directory"

CS2_CFG_DIR="$HOME/.local/share/Steam/steamapps/common/Counter-Strike Global Offensive/game/csgo/cfg"

if [[ -d "$CS2_CFG_DIR" ]]; then
    ok "CS2 cfg directory already exists"
else
    mkdir -p "$CS2_CFG_DIR" && ok "Created: $CS2_CFG_DIR"
fi

# -----------------------------------------------------------------------------
# TASK 2.4 — Write autoexec.cfg
# Spec: cs2-autoexec — FPS and Rendering Settings + Network Rate Optimization
# -----------------------------------------------------------------------------
log "Task 2.4 — Writing autoexec.cfg"

AUTOEXEC="$CS2_CFG_DIR/autoexec.cfg"

if [[ -f "$AUTOEXEC" ]]; then
    warn "autoexec.cfg already exists — backing up to autoexec.cfg.bak"
    cp "$AUTOEXEC" "${AUTOEXEC}.bak"
fi

cat > "$AUTOEXEC" << 'EOF'
// CS2 Performance Autoexec
// Generated by cs2-perf-optimization

// FPS — uncap and show counter for verification
fps_max 0
cl_showfps 1

// Rendering — disable dynamic lighting for performance
r_dynamic 0

// Network — tuned for 128-tick servers
rate 786432
cl_cmdrate 128
cl_updaterate 128
cl_interp_ratio 1
cl_interp 0
EOF

ok "autoexec.cfg written to: $AUTOEXEC"

# -----------------------------------------------------------------------------
# TASK 2.5 — Verify autoexec file is in place
# -----------------------------------------------------------------------------
log "Task 2.5 — Verifying autoexec.cfg"

if [[ -f "$AUTOEXEC" ]]; then
    ok "autoexec.cfg exists at correct path ✓"
    echo "      Content preview:"
    grep -v "^//" "$AUTOEXEC" | grep -v "^$" | sed 's/^/        /'
else
    warn "autoexec.cfg not found at expected path"
fi

# -----------------------------------------------------------------------------
# TASK 2.6 — Print CS2 launch options (manual step — Steam UI required)
# Spec: cs2-launch-options — Optimized Launch String for App ID 730
# -----------------------------------------------------------------------------
log "Task 2.6 — CS2 Steam launch options (manual step)"

echo ""
echo -e "${BOLD}  ► MANUAL STEP REQUIRED ◄${NC}"
echo ""
echo "  Open Steam and set the following launch options for Counter-Strike 2:"
echo ""
echo -e "  ${BOLD}Steam → Counter-Strike 2 → Properties → Launch Options:${NC}"
echo ""
echo "    gamemoderun %command% -novid -high -threads 4 +fps_max 0 +exec autoexec"
echo ""
echo "  Copy the line above exactly."
echo ""

# -----------------------------------------------------------------------------
# SUMMARY
# -----------------------------------------------------------------------------
echo -e "${BOLD}=== Phase 2 Complete ===${NC}"
echo ""
echo "Changes applied:"
echo "  • gamemoded.service — enabled (user service, starts at login)"
echo "  • loginctl linger   — enabled (gamemoded starts at boot)"
echo "  • /etc/gamemode.ini — written (renice=-10, ioprio=0, no screensaver)"
echo "  • CS2 cfg directory — created"
echo "  • autoexec.cfg      — written (fps_max 0, r_dynamic 0, 128-tick network)"
echo ""
echo -e "${YELLOW}Pending manual step:${NC}"
echo "  Set launch options in Steam UI (see Task 2.6 output above)"
echo ""
echo "Rollback:"
echo "  Gamemode:  systemctl --user disable --now gamemoded"
echo "  Autoexec:  rm '$AUTOEXEC'"
echo "  Launch:    Clear field in Steam → CS2 → Properties → Launch Options"
echo ""
